import fs from 'node:fs';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {ObservatoryDemo} from '../reference-apps/versioned-risk-scoring/demo/demo-engine.mjs';

execFileSync(process.execPath, ['scripts/build-observatory-demo.mjs'], {stdio: 'inherit'});
const catalog = JSON.parse(fs.readFileSync('build/observatory-demo/catalog.json'));
const model = new ObservatoryDemo(catalog, () => '2026-10-03T00:00:00Z');
const act = (action, extra) => model.act(action, extra);
const latest = () => model.state.requests.at(-1);
assert.throws(() => act('invoke'), /Activate/);
assert.throws(() => act('rollback'), /previously active/);
act('install', {version: 'v1'});
assert.equal(model.state.deployments[0].state, 'STANDBY');
assert.equal(model.state.activeEligible, false);
assert.throws(() => act('install', {version: 'v1'}), /already installed/);
act('activate', {version: 'v1'});
act('invoke', {sample: 'STANDARD'});
assert.equal(latest().decision, 'REVIEW');
assert.equal(latest().score.toFixed(2), '0.73');
act('invoke', {sample: 'LOW'});
assert.equal(latest().decision, 'ALLOW');
act('install', {version: 'v2'});
assert.equal(model.state.canRollback, false, 'STANDBY alone cannot establish a previous active version');
const held = act('invoke', {sample: 'STANDARD', mode: 'hold'}).id;
assert.equal(latest().score, null);
assert.equal(latest().decision, 'WITHHELD');
assert.throws(() => act('invoke'), /Release/);
act('activate', {version: 'v2'});
act('invoke', {sample: 'HIGH'});
assert.equal(latest().decision, 'REJECT');
act('release', {requestId: held});
const old = model.state.requests.find(r => r.id === held);
assert.equal(old.version, 'v1');
assert.equal(old.score.toFixed(2), '0.73');
assert.equal(old.decision, 'REVIEW');
act('invoke', {mode: 'crash'});
assert.equal(latest().executionState, 'OUTCOME_UNKNOWN');
assert.equal(latest().score, null);
assert.equal(latest().decision, 'WITHHELD');
assert.equal(model.state.activeEligible, false);
assert.throws(() => act('invoke'), /Activate/);
const oldNonce = model.state.deployments[0].realization.launchNonce;
act('rollback');
assert.equal(model.state.activeVersion, 'v1');
assert.notEqual(model.state.deployments.at(-1).realization.launchNonce, oldNonce);
assert.equal(model.state.deployments.at(-1).purpose, 'FRESH_ROLLBACK');
act('invoke', {sample: 'LOW'});
assert.equal(latest().decision, 'ALLOW');
assert.throws(() => model.receipt(), /Close/);
act('close');
assert.equal(model.state.observedLiveWorkers, 0);
assert.match(model.receipt().scope, /Browser-only simulation/);
assert.notEqual(model.receipt().schemaVersion, 'jpyxis.io/risk-host-receipt/v1alpha1');
assert.throws(() => act('install', {version: 'v1'}), /Reset/);
model.reset();
assert.equal(model.state.requests.length, 0);
assert.equal(model.state.deployments.length, 0);
act('install', {version: 'v1'}); act('activate', {version: 'v1'});
act('invoke', {mode: 'hold'}); act('close');
assert.equal(latest().canRelease, false);
assert.equal(latest().decision, 'WITHHELD');

const output = 'build/observatory-demo';
assert.equal(fs.readFileSync(`${output}/style.css`, 'utf8'), fs.readFileSync('reference-apps/versioned-risk-scoring/host-java/src/main/resources/observatory/style.css', 'utf8').replaceAll('\r\n', '\n'));
const js = fs.readFileSync(`${output}/app.js`, 'utf8');
assert.ok(!js.includes('/api/'));
assert.ok(!js.includes('LOOPBACK SESSION'));
assert.ok(!js.includes('setInterval'));
assert.match(js, /BROWSER SIMULATION/);
const html = fs.readFileSync(`${output}/index.html`, 'utf8');
assert.match(html, /INTERACTIVE DEMO · BROWSER ONLY/);
assert.match(html, /no Java or Python process runs/);
assert.ok(!html.includes('href="/style.css"'));
assert.ok(!html.includes('src="/app.js"'));
console.log('PASS: demo lifecycle, pinned cutover, policy samples, UNKNOWN, fresh rollback, close/export/reset, and production style reuse');
